// The knowledge base: what agents learn, kept as plain Markdown pages with YAML-style frontmatter in
// knowledge/, so any human, agent or wiki tool can read it. Each page names the source files it
// describes and the commit it was last verified at, so a page goes stale when its sources change.
import fs from 'node:fs'
import path from 'node:path'
import { git } from './lib.mjs'

export const TYPES = ['system', 'component', 'decision', 'trap', 'runbook', 'howto', 'glossary', 'playbook']
export const GRADES = ['Established', 'Moderate', 'Preliminary']
const REQUIRED = ['name', 'description', 'type', 'sources', 'verified', 'confidence']

// A small frontmatter reader: "key: value" lines, and "key: [a, b]" lists.
export function frontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/)
  if (!m) return null
  const meta = {}
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^(\w+):\s*(.*)$/)
    if (!kv) continue
    const value = kv[2].trim()
    meta[kv[1]] = /^\[.*\]$/.test(value) ? value.slice(1, -1).split(',').map(v => v.trim()).filter(Boolean) : value
  }
  return meta
}

export function pages(dir) {
  const root = path.join(dir, 'knowledge')
  if (!fs.existsSync(root)) return []
  const out = []
  const walk = rel => {
    for (const e of fs.readdirSync(path.join(root, rel), { withFileTypes: true })) {
      const p = path.join(rel, e.name)
      if (e.isDirectory()) walk(p)
      else if (e.name.endsWith('.md') && !['INDEX.md', 'README.md'].includes(e.name)) {
        const text = fs.readFileSync(path.join(root, p), 'utf8')
        out.push({ file: `knowledge/${p.split(path.sep).join('/')}`, meta: frontmatter(text), text })
      }
    }
  }
  walk('')
  return out
}

// Problems that make a page unusable, and pages whose sources moved on since they were verified.
export function check(dir) {
  const all = pages(dir)
  const names = new Set(all.map(p => p.meta?.name).filter(Boolean))
  const invalid = []
  const stale = []
  for (const p of all) {
    if (!p.meta) {
      invalid.push(`${p.file}: no frontmatter`)
      continue
    }
    const missing = REQUIRED.filter(k => !p.meta[k] || (Array.isArray(p.meta[k]) && !p.meta[k].length))
    if (missing.length) invalid.push(`${p.file}: missing ${missing.join(', ')}`)
    if (p.meta.type && !TYPES.includes(p.meta.type)) invalid.push(`${p.file}: type "${p.meta.type}" is not one of ${TYPES.join(', ')}`)
    if (p.meta.confidence && !GRADES.includes(p.meta.confidence)) invalid.push(`${p.file}: confidence "${p.meta.confidence}" is not one of ${GRADES.join(', ')}`)
    for (const link of p.text.matchAll(/\[\[([^\]]+)\]\]/g)) {
      if (!names.has(link[1])) invalid.push(`${p.file}: links to [[${link[1]}]], which has no page`)
    }
    const sources = Array.isArray(p.meta.sources) ? p.meta.sources : []
    const gone = sources.filter(s => !fs.existsSync(path.join(dir, s)))
    if (gone.length) stale.push({ file: p.file, why: `sources gone: ${gone.join(', ')}` })
    else if (p.meta.verified && sources.length) {
      // cat-file, not "rev-parse sha^{commit}": cmd.exe on Windows eats the caret.
      if (!/^[0-9a-f]{4,40}$/i.test(p.meta.verified) || git(`cat-file -t ${p.meta.verified}`, dir) !== 'commit') {
        stale.push({ file: p.file, why: `verified commit ${p.meta.verified} is unknown` })
        continue
      }
      const changed = git(`diff --name-only ${p.meta.verified} -- ${sources.map(s => `"${s}"`).join(' ')}`, dir)
      if (changed) stale.push({ file: p.file, why: `changed since ${p.meta.verified.slice(0, 7)}: ${changed.split('\n').join(', ')}` })
    }
  }
  return { invalid, stale, count: all.length }
}

// Pages whose sources overlap the given files: what an agent should read before touching them.
export function relevant(dir, files) {
  return pages(dir).filter(p => Array.isArray(p.meta?.sources) &&
    p.meta.sources.some(s => files.some(f => f === s || f.startsWith(s.replace(/\/?$/, '/')))))
}

export function writeIndex(dir) {
  const { stale } = check(dir)
  const staleFiles = new Set(stale.map(s => s.file))
  const lines = ['# Knowledge index', '', 'Generated by `sdlc knowledge index`. Read the pages for the area you are about to change before you change it.', '']
  for (const type of TYPES) {
    const of = pages(dir).filter(p => p.meta?.type === type)
    if (!of.length) continue
    lines.push(`## ${type}`, '')
    for (const p of of) lines.push(`- [${p.meta.name}](${p.file.replace(/^knowledge\//, '')}): ${p.meta.description} (${p.meta.confidence}${staleFiles.has(p.file) ? ', STALE' : ''})`)
    lines.push('')
  }
  fs.mkdirSync(path.join(dir, 'knowledge'), { recursive: true })
  fs.writeFileSync(path.join(dir, 'knowledge', 'INDEX.md'), lines.join('\n'))
  return lines.length
}
